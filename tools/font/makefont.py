UPM, PX, ADV = 1000, 120, 6           # a pixel is 120 units, glyphs are 5 wide on a 6-pixel advance
ASC = 7 * PX + 80

def glyph(rows):
    pen = TTGlyphPen(None); rows = rows.split(' ')
    for r, line in enumerate(rows):
        y1 = (7 - r) * PX; y0 = y1 - PX; c = 0
        while c < len(line):
            if line[c] == '#':
                s = c
                while c < len(line) and line[c] == '#': c += 1
                x0, x1 = s * PX + PX // 2, c * PX + PX // 2
                pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
            else: c += 1
    return pen.glyph()

names = ['.notdef']; glyphs = {'.notdef': glyph(G['?'])}; cmap = {}; metrics = {'.notdef': (ADV * PX, 0)}
for ch, rows in G.items():
    n = 'g%04x' % ord(ch); names.append(n); glyphs[n] = glyph(rows); metrics[n] = (ADV * PX, 0); cmap[ord(ch)] = n
    if 'A' <= ch <= 'Z': cmap[ord(ch.lower())] = n
fb = FontBuilder(UPM, isTTF=True)
fb.setupGlyphOrder(names); fb.setupCharacterMap(cmap); fb.setupGlyf(glyphs); fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=ASC, descent=-200)
fb.setupNameTable({'familyName': 'ToofanPx', 'styleName': 'Regular'})
fb.setupOS2(sTypoAscender=ASC, sTypoDescender=-200, usWinAscent=ASC, usWinDescent=200)
fb.setupPost()
buf = io.BytesIO(); fb.save(buf); data = buf.getvalue()
out = os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'data', 'pixelfont.js')
open(out, 'w').write("/* data: ToofanPx, the game's pixel 'code terminal' font (5x7 square pixels), built by tools/font/makefont.py. TrueType, base64. */\n'use strict';\nmodule.exports = { TTF: '%s' };\n" % base64.b64encode(data).decode())
print('wrote', out, len(data), 'bytes,', len(cmap), 'characters')
